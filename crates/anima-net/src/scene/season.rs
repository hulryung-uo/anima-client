/// Season ids as they arrive in 0xBC (`SeasonChange`): 0 spring, 1 summer,
/// 2 fall, 3 winter, 4 desolation. Summer has no rows at all — it IS the art
/// as shipped — and only winter remaps land.
const SPRING: u8 = 0;
const FALL: u8 = 2;
const WINTER: u8 = 3;
const DESOLATION: u8 = 4;

/// The season the SCENE is drawn with. Normally the world's own (0xBC, plus
/// the client-side flip to desolation while dead, `World::season`), but
/// `ANIMA_SEASON=0..4` pins it.
///
/// That override is a test rig, not a convenience, and it earns its keep twice
/// over. Winter is the only season that remaps land — all 312 rows — and no GM
/// command reaches it: a shard's season is fixed per-map at `RegisterMap`, and
/// ServUO exposes no runtime setter. It is also the sharpest possible
/// fault-injection for this module: pinned to a season the SERVER disagrees
/// with, any leak of the remap into `w`/`sz`/`li`/`h`/`pf` stops being subtle
/// and becomes a denied step or a rubber-band on the first wall you walk into.
pub(super) fn scene_season(world_season: u8) -> u8 {
    static OVERRIDE: std::sync::OnceLock<Option<u8>> = std::sync::OnceLock::new();
    OVERRIDE
        .get_or_init(|| {
            std::env::var("ANIMA_SEASON")
                .ok()
                .and_then(|v| v.trim().parse::<u8>().ok())
                .filter(|&s| s <= 4)
        })
        .unwrap_or(world_season)
}

fn lookup(table: &[(u16, u16)], g: u16) -> u16 {
    match table.binary_search_by_key(&g, |&(k, _)| k) {
        Ok(i) => table[i].1,
        Err(_) => g,
    }
}

/// The land graphic to DRAW for `g` in `season`. Never feed this to a
/// walkability check — see the module doc.
pub(super) fn land_draw_graphic(season: u8, g: u16) -> u16 {
    if season == WINTER {
        lookup(&WINTER_LAND, g)
    } else {
        g
    }
}

/// The static graphic to DRAW for `g` in `season`. Applies to real statics and
/// to multi components (ClassicUO overrides `UpdateGraphicBySeason` on `Land`,
/// `Static` and `Multi`) but NOT to dynamic server items — `Item` inherits the
/// no-op base, so a server-placed tree keeps its graphic in winter. Never feed
/// this to a walkability check.
pub(super) fn static_draw_graphic(season: u8, g: u16) -> u16 {
    match season {
        SPRING => lookup(&SPRING_STATIC, g),
        FALL => lookup(&FALL_STATIC, g),
        WINTER => lookup(&WINTER_STATIC, g),
        DESOLATION => lookup(&DESOLATION_STATIC, g),
        _ => g, // summer (1) and anything out of range: as shipped
    }
}
