//! Seasonal graphic substitution (ClassicUO `Data/Client/seasons.txt`).
//!
//! UO does not ship winter art as a separate map: it ships ONE map and a
//! substitution table. When the season changes the *client* swaps a tile's
//! graphic for its seasonal twin — grass 573 becomes snow 1861, a green tree
//! becomes a bare one — and the server never learns about it. ServUO's
//! `Map.Season` is a plain int written once at `RegisterMap` and read in
//! exactly one place (`Mobile.GetSeason`, to fill the 0xBC it sends you); its
//! movement code (`MovementImpl`) reads the RAW map/statics ids and never
//! consults the season at all.
//!
//! That asymmetry dictates the whole design here, and it is a DELIBERATE
//! DIVERGENCE FROM CLASSICUO. ClassicUO stores the substitution *in* the
//! object's `Graphic` field (`Land.UpdateGraphicBySeason` etc.), and every one
//! of its tiledata accessors then indexes the REMAPPED id (`Land.cs`:
//! `TileDataLoader.Instance.LandData[Graphic]`) — including the ones
//! `Pathfinder.CreateItemList` reads. So ClassicUO genuinely pathfinds on
//! substituted tiledata, and 29 of the 312 winter land rows flip IMPASSABLE
//! (27 of them impassable → passable). Against a ServUO shard that is simply a
//! client-side disagreement with the server's own walkability.
//!
//! We keep the two apart instead: this table is consulted ONLY when writing a
//! DRAW field into the scene JSON. `World` — the single source of truth for
//! pathing and for the agent contract — keeps original graphics, so the brain
//! and the walk checks see what the server sees. See `DESIGN.md` D3.
//!
//! The table itself is byte-identical in ClassicUO's shipped
//! `Data/Client/seasons.txt` and in the 498 `WriteLine` literals of
//! `SeasonManager.CreateDefaultSeasonsFile` that regenerate it; both were
//! parsed independently and reconciled before this file was written. Row
//! syntax is `<season>,<kind>,<from>,<to>`, and `LoadSeasonFile` stores it as
//! `arr[from] = to`, read back as `arr[g] == 0 ? g : arr[g]` — i.e. ONE hop,
//! never a chain. That matters: 3244 → 6093 and 3245 → 3379 are both winter
//! rows, and 3379 → 6093 is another, so a fixed-point loop would silently
//! over-substitute. Each bucket below is sorted by key for `binary_search`
//! (verified free of duplicate keys, so the sort is lossless).

